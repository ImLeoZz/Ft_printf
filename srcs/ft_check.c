#include <stddef.h>

size_t	ft_gettype(char *p)
{
	size_t	k;

	k = 0;
	if (p[k] == 'c' || p[k] == 'd' || p[k] == 'i'
		|| p[k] == 'u' || p[k] == 'x' || p[k] == 'X')
		return (4);
	else if (p[k] == 's' || p[k] == 'p')
		return (8);
	return (0);
}
